"""Build the production LiteLLM config (k8s/litellm_config.prod.yaml) from the development one (litellm_config.yaml).

The development config keeps message logging on (prompts visible in Langfuse/Jaeger while debugging) and leaves
/metrics unauthenticated (Prometheus scrapes it inside the Compose network). Neither is acceptable for production
traffic (production-readiness audit M6). This script copies the development config and switches exactly these keys,
keeping every comment and every other line byte for byte, so the two files cannot drift apart:

    litellm_settings.turn_off_message_logging          -> true
    litellm_settings.require_auth_for_metrics_endpoint -> true

    python k8s/build_prod_config.py           # write k8s/litellm_config.prod.yaml
    python k8s/build_prod_config.py --check   # CI: fail if the committed file is stale or a production key is wrong

With require_auth_for_metrics_endpoint the Prometheus scrape job needs a LiteLLM key (bearer token).
"""

import argparse
import re
import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parent.parent
SOURCE = ROOT / "litellm_config.yaml"
TARGET = ROOT / "k8s" / "litellm_config.prod.yaml"

# litellm_settings keys and the value production requires.
PRODUCTION_SETTINGS = {
    "turn_off_message_logging": True,
    "require_auth_for_metrics_endpoint": True,
}

HEADER = (
    "# GENERATED by k8s/build_prod_config.py from litellm_config.yaml - do not edit by hand.\n"
    "# Production overrides: turn_off_message_logging=true, require_auth_for_metrics_endpoint=true.\n"
    "# Regenerate after changing litellm_config.yaml: python k8s/build_prod_config.py\n\n"
)


def build(source_text: str) -> str:
    text = source_text
    for key, value in PRODUCTION_SETTINGS.items():
        pattern = re.compile(rf"^(\s+{re.escape(key)}:\s*)\S+(.*)$", re.MULTILINE)
        text, count = pattern.subn(lambda m: f"{m.group(1)}{str(value).lower()}{m.group(2)}", text)
        if count != 1:
            raise SystemExit(f"expected exactly one '{key}:' line in {SOURCE.name}, found {count}")
    return HEADER + text


def problems(config_text: str) -> list[str]:
    settings = (yaml.safe_load(config_text) or {}).get("litellm_settings") or {}
    return [
        f"litellm_settings.{key} is {settings.get(key)!r}, production requires {value!r}"
        for key, value in PRODUCTION_SETTINGS.items()
        if settings.get(key) is not value
    ]


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="verify the committed file instead of writing it")
    args = parser.parse_args(argv)
    expected = build(SOURCE.read_text(encoding="utf-8"))
    found = problems(expected)
    if found:
        print("\n".join(found), file=sys.stderr)
        return 1
    if args.check:
        if not TARGET.exists() or TARGET.read_text(encoding="utf-8") != expected:
            print(f"{TARGET.relative_to(ROOT)} is stale: run python k8s/build_prod_config.py", file=sys.stderr)
            return 1
        print(f"{TARGET.relative_to(ROOT)} is up to date and production-safe")
        return 0
    TARGET.write_text(expected, encoding="utf-8", newline="\n")
    print(f"wrote {TARGET.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
